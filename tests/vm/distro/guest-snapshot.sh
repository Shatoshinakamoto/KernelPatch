# guest-snapshot.sh - before/after record of everything install.sh may touch,
# for the clean-removal check in run-install-test.sh. Runs in the guest.
#
#   guest-snapshot.sh snap > FILE          "sha256  path" for every file/link
#   guest-snapshot.sh compare BEFORE AFTER PKGS-BEFORE
#       prints each path that differs, except files of distro packages
#       installed since PKGS-BEFORE (the runtime dependencies); exit 1 if any
set -uo pipefail
DIRS=(/usr/bin /usr/sbin /usr/libexec /usr/lib/x86_64-linux-gnu/security
	/lib/systemd/system /etc/systemd/system /etc/secure_sudo /etc/default
	/etc/pam.d /boot /lib/modules /usr/share/doc/secure-sudo
	/usr/share/secure-sudo /var/lib/secure_sudo)

# grubenv is GRUB's own state, and grub.cfg is regenerated by every kernel
# install and removal: the image's copy was made on another machine, so a
# fresh regeneration never matches it byte for byte. run-install-test.sh
# compares grub.cfg with what grub-mkconfig produced before the install.
snap() {
	local d
	for d in "${DIRS[@]}"; do
		[ -e "$d" ] && find "$d" -xdev \( -type f -o -type l \) \
			! -path /boot/grub/grubenv ! -path /boot/grub/grub.cfg -print0
	done | sort -z | xargs -0 -r sha256sum 2>/dev/null
}

compare() { # before after pkgs-before
	local t; t="$(mktemp -d)"
	dpkg-query -W -f '${Package}\n' | sort > "$t/pkgs"
	comm -13 "$3" "$t/pkgs" > "$t/new"
	echo "packages installed since: $(tr '\n' ' ' < "$t/new")"
	while read -r p; do dpkg -L "$p"; done < "$t/new" > "$t/owned" 2>/dev/null
	# usrmerge: dpkg may list /bin/x for what is found at /usr/bin/x
	{ cat "$t/owned"
	  sed -E 's#^/(bin|sbin|lib|lib64)/#/usr/\1/#' "$t/owned"
	  sed -E 's#^/usr/lib/systemd/#/lib/systemd/#' "$t/owned"
	} | sort -u > "$t/owned.all"
	mv "$t/owned.all" "$t/owned"
	diff "$1" "$2" | sed -n -E 's/^([<>]) [0-9a-f]{64}  (.*)$/\1 \2/p' |
		while read -r side path; do
			grep -qxF -- "$path" "$t/owned" || echo "$side $path"
		done | sort -u > "$t/left"
	if [ -s "$t/left" ]; then
		echo "differences ('<' only before, '>' only after or changed):"
		cat "$t/left"; rm -rf "$t"; return 1
	fi
	echo "no differences outside those packages"
	rm -rf "$t"
}

case "${1:-}" in
snap) snap ;;
compare) compare "${2:?BEFORE}" "${3:?AFTER}" "${4:?PKGS-BEFORE}" ;;
*) echo "usage: $0 snap | compare BEFORE AFTER PKGS-BEFORE" >&2; exit 2 ;;
esac
